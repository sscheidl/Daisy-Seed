#!/usr/bin/env python3
"""Generate the SQ parameter tables and the editors' contract files.

Sources: contracts/parameters.json (Acid Seq components) and the further SQ products in
EXTRA_SOURCES (Streichwurst). Each source gets its own C++ table header; the browser
contract (sq_contract.js) and the JUCE labels (SqLabels.h) contain all components.

    python sequencers/step-seq/tools/gen_params.py          # write the files
    python sequencers/step-seq/tools/gen_params.py --check  # fail if one is out of date
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SOURCE = HERE / 'contracts' / 'parameters.json'
TARGET = HERE / 'include' / 'step_seq' / 'param_table.h'
ROOT = HERE.parent.parent
# Further SQ products: (contract, table header, product name). Their tables reuse the
# types of step_seq/param_table.h, so their type, unit and flag lists must be identical.
EXTRA_SOURCES = [
    (ROOT / 'instruments' / 'streichwurst' / 'contracts' / 'parameters.json',
     ROOT / 'instruments' / 'streichwurst' / 'include' / 'streichwurst' / 'param_table.h', 'Streichwurst'),
]


def all_components():
    """Components of every contract, Acid Seq first; names must be unique."""
    base = json.loads(SOURCE.read_text(encoding='utf-8'))
    components = dict(base['components'])
    for source, _, _ in EXTRA_SOURCES:
        data = json.loads(source.read_text(encoding='utf-8'))
        for key in ('units', 'types', 'flags'):
            if data[key] != base[key]:
                raise SystemExit(f'{source}: "{key}" differs from {SOURCE}')
        for name, spec in data['components'].items():
            if name in components:
                raise SystemExit(f'{source}: component {name} defined twice')
            components[name] = spec
    return components


def generate_extra(source, product):
    """Tables of a further SQ product; types and helpers come from step_seq/param_table.h."""
    data = json.loads(source.read_text(encoding='utf-8'))
    types = {name: i for i, name in enumerate(data['types'])}
    units = {name: i for i, name in enumerate(data['units'])}
    lines = [
        '#pragma once',
        '// SPDX-License-Identifier: MIT',
        f'// GENERATED by sequencers/step-seq/tools/gen_params.py from {source.relative_to(ROOT).as_posix()}.',
        f'// Do not edit. Stable parameter IDs and CC plan of the {product} components.',
        '#include "step_seq/param_table.h"',
        '',
        'namespace sq {',
        '',
    ]
    for component, spec in data['components'].items():
        name = ident(component)
        for p in spec['parameters']:
            if len(p['key']) > 16:
                raise SystemExit(f"{component}.{p['key']}: key longer than 16 characters (SQ str)")
            if p['type'] == 'enum':
                keys = ', '.join(f'"{k}"' for k in p['enum'])
                lines.append(f"inline constexpr const char* k{name}Enum{p['id']}[] = {{{keys}}};")
        lines.append(f'inline constexpr ParamDesc k{name}Params[] = {{')
        for p in spec['parameters']:
            flags = sum(data['flags'][f] for f in p.get('flags', []))
            cc = p['cc'] if p['cc'] is not None else 'kNoCc'
            enum = (f"{len(p['enum'])}, k{name}Enum{p['id']}" if p['type'] == 'enum' else '0, nullptr')
            values = ', '.join(str(int(round(p[k] * 1000))) for k in ('min', 'max', 'default'))
            lines.append(f"    {{{p['id']}, \"{p['key']}\", {types[p['type']]}, {units[p['unit']]}, {flags}, "
                         f"{values}, {cc}, {enum}}},")
        lines.append('};')
        lines.append(f'inline constexpr ComponentParams k{name}Component = {{"{component}", {spec["schema"]}, '
                     f'k{name}Params, uint8_t(sizeof(k{name}Params) / sizeof(k{name}Params[0]))}};')
        lines.append('')
    lines += ['} // namespace sq', '']
    return '\n'.join(lines)


def ident(component):
    return ''.join(part.capitalize() for part in component.replace('-', '_').split('_'))


def generate():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    types = {name: i for i, name in enumerate(data['types'])}
    units = {name: i for i, name in enumerate(data['units'])}
    lines = [
        '#pragma once',
        '// SPDX-License-Identifier: MIT',
        '// GENERATED by tools/gen_params.py from contracts/parameters.json. Do not edit.',
        '// Stable parameter IDs and CC plan of all Acid Seq components (PARAMETERS.md).',
        '#include <cstdint>',
        '',
        'namespace sq {',
        '',
        'enum ParamType : uint8_t { ' + ', '.join(f'Type{ident(t)} = {i}' for t, i in types.items()) + ' };',
        'enum ParamUnit : uint8_t { ' + ', '.join(f'Unit{ident(u)} = {i}' for u, i in units.items()) + ' };',
        f"enum ParamFlag : uint8_t {{ FlagReadonly = {data['flags']['readonly']}, FlagLog = {data['flags']['log']} }};",
        'constexpr uint8_t kNoCc = 127;',
        '',
        'struct ParamDesc {',
        '    uint16_t id;',
        '    const char* key;',
        '    uint8_t type, unit, flags;',
        '    int32_t min, max, def; // milli-units',
        '    uint8_t cc;',
        '    uint8_t enum_count;',
        '    const char* const* enum_keys;',
        '};',
        '',
        'struct ComponentParams {',
        '    const char* id;',
        '    uint8_t schema;',
        '    const ParamDesc* params;',
        '    uint8_t count;',
        '};',
        '',
    ]
    for component, spec in data['components'].items():
        name = ident(component)
        for p in spec['parameters']:
            if p['type'] == 'enum':
                keys = ', '.join(f'"{k}"' for k in p['enum'])
                lines.append(f"inline constexpr const char* k{name}Enum{p['id']}[] = {{{keys}}};")
        lines.append(f'inline constexpr ParamDesc k{name}Params[] = {{')
        for p in spec['parameters']:
            flags = sum(data['flags'][f] for f in p.get('flags', []))
            cc = p['cc'] if p['cc'] is not None else 'kNoCc'
            enum = (f"{len(p['enum'])}, k{name}Enum{p['id']}" if p['type'] == 'enum' else '0, nullptr')
            values = ', '.join(str(int(round(p[k] * 1000))) for k in ('min', 'max', 'default'))
            lines.append(f"    {{{p['id']}, \"{p['key']}\", {types[p['type']]}, {units[p['unit']]}, {flags}, "
                         f"{values}, {cc}, {enum}}},")
        lines.append('};')
        lines.append(f'inline constexpr ComponentParams k{name}Component = {{"{component}", {spec["schema"]}, '
                     f'k{name}Params, uint8_t(sizeof(k{name}Params) / sizeof(k{name}Params[0]))}};')
        lines.append('')
    lines += [
        '// Clamp a wire value to the descriptor; integer types round to whole units.',
        'inline int32_t Constrain(const ParamDesc& d, int32_t value) {',
        '    if(value < d.min)',
        '        value = d.min;',
        '    if(value > d.max)',
        '        value = d.max;',
        '    if(d.type != TypeFloat) {',
        '        const int32_t whole = (value >= 0 ? value + 500 : value - 500) / 1000 * 1000;',
        '        value = whole < d.min ? d.min : (whole > d.max ? d.max : whole);',
        '    }',
        '    return value;',
        '}',
        '',
        'inline const ParamDesc* FindParam(const ComponentParams& c, uint16_t id) {',
        '    for(uint8_t i = 0; i < c.count; ++i)',
        '        if(c.params[i].id == id)',
        '            return &c.params[i];',
        '    return nullptr;',
        '}',
        '',
        '} // namespace sq',
        '',
    ]
    return '\n'.join(lines)


WEB_TARGET = HERE.parent.parent / 'editors' / 'mod-on-daisy' / 'web' / 'sq_contract.js'


def generate_web():
    """The contract for the browser panel: German labels and the offline demo."""
    body = json.dumps(all_components(), ensure_ascii=False, indent=1)
    return ('// GENERATED by sequencers/step-seq/tools/gen_params.py from the SQ parameter contracts.\n'
            '// Parameter contract of the SQ components (Acid Seq, Streichwurst) for the browser panel.\n'
            '(function (root) {\n'
            '  const contract = ' + body.replace('\n', '\n  ') + ';\n'
            "  if (typeof module === 'object' && module.exports) module.exports = contract;\n"
            '  else root.SqContract = contract;\n'
            "})(typeof self !== 'undefined' ? self : this);\n")


LABELS_TARGET = HERE.parent.parent / 'editors' / 'mod-on-daisy' / 'src' / 'core' / 'SqLabels.h'


def cstr(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def generate_labels():
    """German panel labels for the JUCE editor (UTF-8), keyed by component and parameter key."""
    lines = ['#pragma once',
             '// GENERATED by sequencers/step-seq/tools/gen_params.py from the SQ parameter contracts.',
             '// German labels of the SQ parameters (Acid Seq, Streichwurst) for the JUCE panel (UTF-8).',
             '#include <cstring>',
             '',
             'namespace editor {',
             '',
             'struct SqLabel {',
             '    const char* component;',
             '    const char* key;',
             '    const char* label;',
             '    const char* const* enum_labels;',
             '    int enum_count;',
             '    const char* page; // panel page of products that group by page ("" = by component)',
             '};',
             '']
    entries = []
    for component, spec in all_components().items():
        for p in spec['parameters']:
            name = 'nullptr'
            count = 0
            if p['type'] == 'enum':
                name = f"kSqEnum{ident(component)}{p['id']}"
                lines.append(f"inline constexpr const char* {name}[] = {{{', '.join(cstr(l) for l in p['enum_labels'])}}};")
                count = len(p['enum_labels'])
            entries.append(f"    {{{cstr(component)}, {cstr(p['key'])}, {cstr(p['label'])}, {name}, {count}, "
                           f"{cstr(p.get('page', ''))}}},")
    lines += ['', 'inline constexpr SqLabel kSqLabels[] = {'] + entries + ['};', '',
              'inline const SqLabel* FindSqLabel(const char* component, const char* key) {',
              '    for(const SqLabel& l : kSqLabels)',
              '        if(std::strcmp(l.component, component) == 0 && std::strcmp(l.key, key) == 0)',
              '            return &l;',
              '    return nullptr;',
              '}',
              '',
              '} // namespace editor',
              '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = [(TARGET, generate()), (WEB_TARGET, generate_web()), (LABELS_TARGET, generate_labels())]
    outputs += [(target, generate_extra(source, product)) for source, target, product in EXTRA_SOURCES]
    if args.check:
        for path, text in outputs:
            if path.read_text(encoding='utf-8') != text:
                parser.exit(1, f'{path.name} is out of date: run tools/gen_params.py\n')
        print("PASS: param_table.h files, sq_contract.js and SqLabels.h match the SQ contracts")
    else:
        for path, text in outputs:
            path.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
