#!/usr/bin/env python3
"""Byte vectors of the SD share protocols from the Python reference (Daisy Diagnostic 0.6.0).

    python3 tests/sd_vectors.py            # rewrites tests/sd_share_vectors.txt
    python3 tests/sd_vectors.py --check    # fails if the file differs from the reference

The C++ test (tests/test_sd_share.cpp) reads the file and must produce or decode the same
bytes (SD_SHARE_PORT.md § 2, phase 2 byte cross-check). Lines: `<name> <hex> [key=value ...]`.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "diagnostics" / "windows"))

from daisy_diag import looper as lp  # noqa: E402
from daisy_diag import nebulae as nb  # noqa: E402
from daisy_diag import protocol as p  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parent / "sd_share_vectors.txt"


def hx(data: bytes) -> str:
    return data.hex().upper()


def lines() -> list[str]:
    out = ["# Generated by tests/sd_vectors.py from diagnostics/windows/daisy_diag; do not edit."]
    tokens = [bytes([1, 2, 3, 4]), bytes([0x7F, 0, 0x40, 0x01]), bytes([0, 0, 0, 0])]
    for name, mod in (("nebulae", nb), ("looper", lp)):
        out.append(f"{name}.status_request {hx(mod.status_request())}")
        for token in tokens:
            for confirm in (0, 1):
                out.append(f"{name}.share_request {hx(mod.share_request(bool(confirm), token))} "
                           f"confirm={confirm} token={hx(token)}")
        # SHARE replies the firmware may send, decoded by the reference.
        results = {0: "ACCEPTED", 1: "CONFIRM_REQUIRED", 2: "BUSY", 3: "NO_CARD", 4: "BAD_REQUEST", 5: "SAVING"}
        for code, _ in results.items():
            raw = mod.SYSEX_PREFIX + bytes([1, 0x42, code, 9, 8, 7, 6, 0xF7])
            kind, (result, token) = mod.parse_reply(raw)
            out.append(f"{name}.parse.share {hx(raw)} result={result} token={hx(token)}")
        raw = mod.SYSEX_PREFIX + bytes([1, 0x7F, 0x33, 2, 0xF7])
        kind, (command, code) = mod.parse_reply(raw)
        out.append(f"{name}.parse.error {hx(raw)} command={command} code={code}")
    # STATUS replies: the same bytes as the firmware tests.
    data = [0, 2, 0, 0, 1 | 16, 2, 3, 2, 16, 7, 0, 0, 0x7F, 0x7F, 3, 4, 0x7F, 0x7F, 127]
    raw = nb.SYSEX_PREFIX + bytes([1, 0x41, *data, 0xF7])
    _, st = nb.parse_reply(raw)
    out.append(f"nebulae.parse.status {hx(raw)} firmware={st.firmware} card={int(st.card)} live={int(st.live)} "
               f"recording={int(st.recording)} loading={int(st.loading)} overrun={int(st.overrun)} "
               f"scanning={int(st.scanning)} bank={st.bank} banks={st.banks} playing_bank={st.playing_bank} "
               f"playing_slot={st.playing_slot} bank_mask={st.bank_mask} slot_mask={st.slot_mask} "
               f"load_error={st.load_error} overruns={st.overruns} peak_load={st.peak_load} busy={int(st.busy)}")
    ms = 87000
    data = [0, 5, 0, 0, 1 | 2 | 4 | 64, 1, 2, ms & 0x7F, ms >> 7 & 0x7F, ms >> 14 & 0x7F, 0x7F, 0x7F, 127]
    raw = lp.SYSEX_PREFIX + bytes([1, 0x41, *data, 0xF7])
    _, st = lp.parse_reply(raw)
    out.append(f"looper.parse.status {hx(raw)} firmware={st.firmware} card={int(st.card)} loop={int(st.loop)} "
               f"unsaved={int(st.unsaved)} saving={int(st.saving)} recording={int(st.recording)} "
               f"importing={int(st.importing)} overrun={int(st.overrun)} save_failed={int(st.save_failed)} "
               f"fault={st.fault} loop_ms={st.loop_ms} overruns={st.overruns} peak_load={st.peak_load} "
               f"busy={int(st.busy)}")
    data = [0, 5, 0, 0, 16 | 32, 0, 0, 0, 0, 0, 0, 0, 0]
    raw = lp.SYSEX_PREFIX + bytes([1, 0x41, *data, 0xF7])
    _, st = lp.parse_reply(raw)
    out.append(f"looper.parse.status {hx(raw)} firmware={st.firmware} card={int(st.card)} loop={int(st.loop)} "
               f"unsaved={int(st.unsaved)} saving={int(st.saving)} recording={int(st.recording)} "
               f"importing={int(st.importing)} overrun={int(st.overrun)} save_failed={int(st.save_failed)} "
               f"fault={st.fault} loop_ms={st.loop_ms} overruns={st.overruns} peak_load={st.peak_load} "
               f"busy={int(st.busy)}")
    # Messages both parsers must reject (test_nebulae.py / test_looper.py).
    rejected = [
        bytes([0xF0, 0x7D, 0x42, 0x4C, 1, 0x41, 0xF7]),                                 # bootloader
        bytes([0xF0, 0x7D, 0x4E, 0x42, 2, 0x41] + [0] * 19 + [0xF7]),                   # version
        bytes([0xF0, 0x7D, 0x4E, 0x42, 1, 0x41] + [0] * 18 + [0xF7]),                   # length
        bytes([0xF0, 0x7D, 0x4E, 0x42, 1, 0x41] + [0, 2, 0, 1] + [0] * 15 + [0xF7]),    # personality
        bytes([0xF0, 0x7D, 0x4E, 0x42, 1, 0x42, 0, 1, 2, 0x90, 4, 0xF7]),               # status byte
        bytes([0xF0, 0x7D, 0x4E, 0x42, 1, 0x55, 0, 0xF7]),                              # unknown command
        bytes([0xF0, 0x7D, 0x4C, 0x50, 2, 0x41] + [0] * 13 + [0xF7]),
        bytes([0xF0, 0x7D, 0x4C, 0x50, 1, 0x41] + [0] * 12 + [0xF7]),
        bytes([0xF0, 0x7D, 0x4C, 0x50, 1, 0x41] + [0, 5, 0, 1] + [0] * 9 + [0xF7]),
        bytes([0xF0, 0x7D, 0x4C, 0x50, 1, 0x42, 0, 1, 2, 0x90, 4, 0xF7]),
        bytes([0xF0, 0x7D, 0x4C, 0x50, 1, 0x55, 0, 0xF7]),
        bytes([0xF0, 0x7D, 0x4D, 0x44, 1, 0, 0x7E, 0, 2, 0, 0, 0x7E, 0xF7]),             # Mod on Daisy monitor
    ]
    for raw in rejected:
        for mod in (nb, lp):
            try:
                mod.parse_reply(raw)
            except nb.NebulaeError:
                continue
            raise SystemExit(f"reference accepted {hx(raw)}")
        out.append(f"reject {hx(raw)}")
    # DDP frames the workflow sends (CRC-16 framing of protocol.py).
    for name, body in (("hello", p.cmd_hello()), ("ping", p.cmd_ping(1)), ("bye", "BYE"),
                       ("reader.status", "READER a=STATUS"), ("reader.share", "READER a=SHARE"),
                       ("reader.return", "READER a=RETURN"), ("neb.status", "NEB a=STATUS"),
                       ("neb.perform", nb.NEBULAE.perform_command), ("looper.status", "LOOPER a=STATUS"),
                       ("looper.perform", lp.LOOPER.perform_command)):
        out.append(f"ddp.{name} {hx(p.build_frame(body))} body={body.replace(' ', '_')}")
    return out


def main() -> int:
    text = "\n".join(lines()) + "\n"
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} differs from the Python reference; run tests/sd_vectors.py", file=sys.stderr)
            return 1
        print(f"PASS: {OUT.name} matches the Python reference ({len(text.splitlines())} lines)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
