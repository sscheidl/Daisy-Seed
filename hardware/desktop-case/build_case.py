"""Build a parametric prototype tray and overlay carrier; all dimensions in mm.

Run in a venv with requirements.txt. No PCB editing, firmware or hardware access.
The STL meshes are generated by exact manifold CSG, not by a visual mock-up.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path

import manifold3d as m
import numpy as np
import trimesh
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

ROOT = Path(__file__).resolve().parent
BOARD = json.loads((ROOT / "board.json").read_text(encoding="utf8"))
W, D = BOARD["width"], BOARD["depth"]
MARGIN, WALL, FLOOR = 9.0, 2.4, 2.8
STANDOFF, LID_THICKNESS = 6.0, 2.4
PCB_BOTTOM = FLOOR + STANDOFF
PCB_TOP = PCB_BOTTOM + BOARD["thickness"]
LID_SCREWS = [(-4.5, -4.5), (201.5, -4.5), (-4.5, 115.5), (201.5, 115.5)]
# Neutrik footprint origin is a pin, not the connector axis: +8.115 mm in X.
AUDIO_AXES = [39.915, 62.4, 140.4, 162.8]
# Generous service apertures deliberately avoid unverified, close-fitting Z cuts.
SERVICE_WINDOWS = [(20, -10, 154, 54), (0, 10, 49, 54), (0, 64, 54, 21), (0, 83, 20, 23),
                   (178, 8, 40, 96), (166, 92, 19, 20)]
KEY_WINDOW = (64, 74.5, 96, 31.5)
TOGGLE_WINDOWS = [(v["x"] - 4.5, v["y"] - 9, 9, 18) for v in BOARD["toggles"]]
STL_FRAME = dict(revision='RH-2026-10-25',
    axes='+X right/MIDI, +Y rear/audio, +Z up/populated side',
    origin='PCB rear-left',source_2d='KiCad: X right, Y toward player',
    source_to_stl='X=x, Y=-y, Z=z; outward face winding preserved')


def box(x, y, z, w, d, h):
    return m.Manifold.cube((w, d, h)).translate((x, y, z))


def cylinder(x, y, z, radius, height, segments=64):
    return m.Manifold.cylinder(height, radius, circular_segments=segments).translate((x, y, z))


def rectangle(x, y, w, d):
    return m.CrossSection.square((w, d)).translate((x, y))


def rounded_rectangle(x, y, w, d, radius):
    return rectangle(x + radius, y + radius, w - 2*radius, d - 2*radius).offset(radius)


def union(parts):
    return m.Manifold.batch_boolean(parts, m.OpType.Add)


def tie_slots():
    slots = []
    for x in AUDIO_AXES:
        slots.extend([(x-6.3, -5.8, 2.6, 5), (x+3.7, -5.8, 2.6, 5)])
    for y in [41.09, 73]:
        slots.extend([(-5.8, y-6.3, 5, 2.6), (-5.8, y+3.7, 5, 2.6)])
    for y in [20.3, 44.3, 68.3]:
        slots.extend([(198.8, y-6.3, 5, 2.6), (198.8, y+3.7, 5, 2.6)])
    slots.extend([(167.3, 112.8, 2.6, 5), (177.3, 112.8, 2.6, 5)])
    return slots


def panel_section(knob_diameter):
    panel = rounded_rectangle(-9, -9, W+18, D+18, 3)
    for x, y, w, d in SERVICE_WINDOWS + [KEY_WINDOW] + TOGGLE_WINDOWS:
        panel -= rectangle(x, y, w, d)
    for p in BOARD["pots"]:
        panel -= m.CrossSection.circle(knob_diameter/2, 96).translate((p["x"], p["y"]))
    for x, y in LID_SCREWS:
        panel -= m.CrossSection.circle(1.7, 48).translate((x, y))
    return panel


def build(knob_diameter, panel_clearance):
    seat = PCB_TOP + panel_clearance
    outer = rounded_rectangle(-9, -9, W+18, D+18, 3)
    inner = rounded_rectangle(-9+WALL, -9+WALL, W+18-2*WALL, D+18-2*WALL, 2)
    base = m.Manifold.extrude(outer, seat) - m.Manifold.extrude(inner, seat).translate((0, 0, FLOOR))
    bosses = [cylinder(x, y, 0, 4, seat) for x, y in LID_SCREWS]
    supports = [cylinder(p['x'], p['y'], FLOOR-.1, 3.5, STANDOFF+.1)
                for p in BOARD['mounts']]
    base += union(bosses + supports)
    # Open-top connector cutouts: the model does not clamp connector housings.
    cut_z = PCB_BOTTOM-1
    cuts = [box(x-11, -10, cut_z, 22, 12, seat+5) for x in AUDIO_AXES]
    cuts += [box(-10, 30, cut_z, 13, 76, seat+5),
             box(W-2, 8, cut_z, 13, 96, seat+5),
             box(163, D-2, cut_z, 24, 13, seat+5)]
    cuts += [box(x, y, -1, w, d, FLOOR+2) for x, y, w, d in tie_slots()]
    for p in BOARD['mounts']:
        cuts.append(cylinder(p['x'], p['y'], -1, 1.7, seat+2))
        # Bottom-access M3 hex nuts, 5.7 mm across flats; no heat-set inserts.
        cuts.append(cylinder(p['x'], p['y'], -.1, 5.7/math.sqrt(3), 2.5, 6))
    for x, y in LID_SCREWS:
        cuts.append(cylinder(x, y, FLOOR, 1.3, seat, 48))
    base -= union(cuts)
    panel = m.Manifold.extrude(panel_section(knob_diameter), LID_THICKNESS)
    # A small coupon checks the actual printed M3 holes and both cap envelopes.
    gauge = box(0, 0, 0, 62, 24, 2.4)
    gauge -= union([cylinder(6, 7, -1, 1.7, 5), cylinder(16, 7, -1, 1.3, 5),
                    cylinder(29, 7, -1, 2.8, 5), box(36, 4.2, -1, 5.6, 5.6, 5),
                    cylinder(12, 18, -1, 5.7/math.sqrt(3), 5, 6),
                    cylinder(52, 12, -1, knob_diameter/2, 5)])
    return {"tray": base, "overlay-frame": panel, "fit-coupon": gauge}, seat


def mesh_of(solid):
    assert solid.status() == m.Error.NoError and solid.volume() > 0
    mesh = solid.to_mesh()
    return trimesh.Trimesh(vertices=np.asarray(mesh.vert_properties)[:, :3],
                           faces=np.asarray(mesh.tri_verts), process=True)


def physical_mesh_of(solid):
    """Map source PCB screen coordinates into a right-handed physical STL frame.

    Source X-right/Y-forward plus Z-up is left-handed. Apply this conversion
    once at export, never in a renderer. trimesh also reverses face winding
    for the negative-determinant affine map, retaining outward normals.
    """
    mesh=mesh_of(solid)
    mesh.apply_transform(np.diag([1.,-1.,1.,1.]))
    assert mesh.is_watertight and mesh.is_winding_consistent and mesh.volume>0
    return mesh


def orientation_footer(c):
    c.setFont('Helvetica',7)
    c.drawString(15*mm,6*mm,'BESTUECKTE OBERSEITE: Audio hinten | Seed links | MIDI rechts | RH 25.10.2026')


def validate(solids, seat, knob_diameter):
    report = {"date": "2026-10-25", "kind": "digital geometry checks",'stl_frame':STL_FRAME,
              "hardware": "NICHT GEMESSEN", "parts": {}}
    for name, solid in solids.items():
        mesh = mesh_of(solid)
        components = len(solid.decompose())
        assert mesh.is_watertight and mesh.is_winding_consistent
        assert components == 1, (name, components)
        assert abs(mesh.bounds[0, 2]) < 1e-5
        report['parts'][name] = dict(watertight=bool(mesh.is_watertight), components=components,
                                    size_mm=np.round(mesh.extents, 4).tolist(),
                                    volume_cm3=round(mesh.volume/1000, 3), triangles=len(mesh.faces))
    tray, frame = solids['tray'], solids['overlay-frame']
    assert (tray ^ frame.translate((0, 0, seat))).volume() < 1e-5
    pcb = m.Manifold.extrude(rounded_rectangle(0, 0, W, D, 2.5), BOARD['thickness'])
    pcb = pcb.translate((0, 0, PCB_BOTTOM))
    for p in BOARD['mounts']:
        pcb -= cylinder(p['x'], p['y'], PCB_BOTTOM-1, p['drill']/2, 5)
    assert (tray ^ pcb).volume() < 1e-5, 'PCB intersects tray'
    # Check full 5 x 5 mm cap envelope and every LED through both cover layers.
    section = panel_section(knob_diameter)
    for p in BOARD['buttons']:
        assert (section ^ rectangle(p['x']-2.8, p['y']-2.8, 5.6, 5.6)).area() < 1e-6
    for p in BOARD['leds']:
        assert (section ^ rectangle(p['x']-1.6, p['y']-.9, 3.2, 1.8)).area() < 1e-6
    report['checks'] = dict(pcb_tray_collision_mm3=0, tray_frame_collision_mm3=0,
                            cap_envelopes_clear=16, leds_clear=16,
                            source_revisions_compared=len(BOARD['sources']))
    report['design_mm'] = dict(floor=FLOOR, wall=WALL, pcb_bottom=PCB_BOTTOM,
                               pcb_top=PCB_TOP, frame_underside=seat,
                               frame_top=seat+LID_THICKNESS, knob_opening=knob_diameter,
                               acrylic_optional=1.0, paper_allowance=0.15)
    report['source_sha256'] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                              for p in [ROOT/'board.json', Path(__file__)]}
    return report


def contour_svg(section, out):
    paths = []
    for contour in section.to_polygons():
        paths.append('M ' + ' L '.join(f'{x+9:.4f},{y+9:.4f}' for x, y in contour) + ' Z')
    text = ('<svg xmlns="http://www.w3.org/2000/svg" width="215mm" height="129mm" '
            'viewBox="0 0 215 129"><title>Overlay cover - prototype cut contours, mm</title>'
            '<path fill="none" stroke="#ff0000" stroke-width="0.1" d="' + ' '.join(paths) + '"/></svg>')
    out.write_text(text, encoding='utf8')


def master_pdf(section, out):
    c = canvas.Canvas(str(out), pagesize=landscape(A4), invariant=1)
    c.setTitle('Desktop Case V1 - Paper on Daisy - 1:1 Passschablone')
    pw, ph = landscape(A4)
    c.setFont('Helvetica-Bold', 17)
    c.drawString(17*mm, ph-19*mm, 'Desktop Case V1 / Paper on Daisy')
    c.setFont('Helvetica', 9)
    c.drawString(17*mm, ph-26*mm, 'PASS-SCHABLONE - Prototyp, Passform am Board NICHT GEMESSEN')
    c.drawString(17*mm, ph-32*mm, 'A4 quer, 100 % / tatsaechliche Groesse. Seitenanpassung AUS. Alle Masse in mm.')
    ox, oy = 41*mm, 43*mm
    c.setLineWidth(.15*mm)
    for contour in section.to_polygons():
        path = c.beginPath()
        for i, (x, y) in enumerate(contour):
            px, py = ox+(x+9)*mm, oy+(120-y)*mm
            (path.moveTo if i == 0 else path.lineTo)(px, py)
        path.close()
        c.drawPath(path)
    c.setFont('Helvetica', 7)
    for p in BOARD['pots']:
        c.drawCentredString(ox+(p['x']+9)*mm, oy+(120-68)*mm, p['ref'])
    for p in BOARD['toggles']:
        c.drawCentredString(ox+(p['x']+9)*mm, oy+(120-84)*mm, p['ref'])
    c.setFont('Helvetica', 6.5)
    for p in BOARD['buttons']:
        if int(p['ref'][1:]) <= 8:
            c.drawCentredString(ox+(p['x']+9)*mm, oy+(120-72)*mm, p['ref'])
        else:
            c.drawCentredString(ox+(p['x']+9)*mm, oy+(120-109)*mm, p['ref'])
    c.setFont('Helvetica', 8)
    c.drawString(17*mm, 29*mm, 'Ein gemeinsames Fenster fuer 16 Kappen und LEDs; 8 Poti- und 2 Schalteroeffnungen.')
    c.drawString(17*mm, 23*mm, 'Kontur fuer Papier und optionale 1-mm-Klarplatte. Vor Laserauftrag Passprobe erforderlich.')
    c.setLineWidth(.3*mm)
    c.line(175*mm, 13*mm, 275*mm, 13*mm)
    for x in [175, 275]:
        c.line(x*mm, 11*mm, x*mm, 15*mm)
    c.setFont('Helvetica', 8)
    c.drawCentredString(225*mm, 17*mm, 'Kontrollstrecke exakt 100 mm')
    orientation_footer(c)
    c.save()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'output')
    parser.add_argument('--knob-opening', type=float, default=14.0)
    parser.add_argument('--panel-clearance', type=float, default=9.0,
                        help='Frame underside above PCB top; design assumption, not measurement')
    args = parser.parse_args()
    if not 12 <= args.knob_opening <= 14.3 or not 8 <= args.panel_clearance <= 15:
        parser.error('Use knob openings 12..14.3 and panel clearance 8..15 mm')
    solids, seat = build(args.knob_opening, args.panel_clearance)
    report = validate(solids, seat, args.knob_opening)
    args.output.mkdir(parents=True, exist_ok=True)
    for name, solid in solids.items():
        physical_mesh_of(solid).export(args.output/f'{name}.stl')
    section = panel_section(args.knob_opening)
    contour_svg(section, args.output/'clear-cover-cut.svg')
    master_pdf(section, args.output/'paper-master-a4.pdf')
    report['artifact_sha256'] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                                for p in sorted(args.output.iterdir())
                                if p.suffix in ['.stl', '.svg', '.pdf']}
    (args.output/'validation.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf8',newline='\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
